def encrypt_filename(filename: str, key_str: str) -> str:
    key = key_str.encode("utf-8")
    filename = filename.lower()
    h = hmac.new(key, filename.encode("utf-8"), hashlib.sha256).digest()
    return h[:16].hex()

def file_id_v2(name: str) -> int:

    if len(name) == 8:
        try:
            return int(name, 16) & 0xFFFFFFFF
        except ValueError:
            pass
    name = name.upper()
    b = name.encode("utf-8")
    if len(b) & 3:
        buflen = len(b) + 1 + 3 - (len(b) & 3)
        buf = bytearray(buflen)
        buf[:len(b)] = b
        a = len(b) & ~3
        c = buf[a]
        buf[len(b)] = len(b) - a
        for i in range(len(b) + 1, buflen):
            buf[i] = c
        return zlib.crc32(bytes(buf)) & 0xFFFFFFFF
    return zlib.crc32(b) & 0xFFFFFFFF

def get_ra2_gmd_mapper():

    global _GMD_MAPPER
    if _GMD_MAPPER is None:
        text = zlib.decompress(base64.b64decode(RA2_GMD_ZLIB_B64)).decode("utf-8")
        mapper = {}
        for rec in csv.reader(io.StringIO(text), delimiter="\t"):
            if not rec:
                continue
            name = rec[0]
            if name:
                mapper[file_id_v2(name)] = name
        _GMD_MAPPER = mapper
    return _GMD_MAPPER

def blowfish_key_from_keysource(keysource: bytes) -> bytes:

    ks = keysource[::-1]
    s0 = pow(int.from_bytes(ks[:40], "big"), BLOWFISH_E, BLOWFISH_N)
    s1 = pow(int.from_bytes(ks[40:], "big"), BLOWFISH_E, BLOWFISH_N)
    key = s1 + (s0 << 312)
    if key == 0:
        return b""
    kb = key.to_bytes((key.bit_length() + 7) // 8, "big")
    return kb[::-1]

def parse_lmd(data: bytes) -> dict:

    if data.startswith(LMD_HEADER):
        names_offset = len(LMD_HEADER) + 20
    elif data.startswith(LMD_FILENAME.encode("utf-8")):
        names_offset = len(LMD_FILENAME) + 20
    else:
        raise ValueError("not a local mix database")
    mapper = {}
    for raw in data[names_offset:].split(b"\x00"):
        if not raw:
            continue
        name = raw.decode("utf-8", errors="ignore").strip()
        if name:
            mapper[file_id_v2(name)] = name
    return mapper

def parse_mix(data: bytes, gmd_mapper: dict):

    if len(data) < 10:
        raise ValueError("mix file too small")
    if struct.unpack_from("<H", data, 0)[0] != 0:
        raise ValueError("not an RA2 MIX format")

    flags = struct.unpack_from("<I", data, 0)[0]
    if flags & MIX_FLAG_ENCRYPTED:
        key = blowfish_key_from_keysource(data[4:84])
        cipher = Blowfish.new(key, Blowfish.MODE_ECB)
        first = cipher.decrypt(data[84:92])
        count = struct.unpack_from("<H", first, 0)[0]
        index_len = (6 + 12 * count + 7) & ~7
        index_end = 84 + index_len
        if index_end > len(data):
            raise ValueError("mix index out of bounds")

        decrypted = b"".join(cipher.decrypt(data[i:i + 8]) for i in range(84, index_end, 8))
        entries_data = decrypted[6:6 + 12 * count]
        body_offset = index_end
    else:
        count = struct.unpack_from("<H", data, 4)[0]
        index_end = 10 + 12 * count
        if index_end > len(data):
            raise ValueError("mix index out of bounds")
        entries_data = data[10:index_end]
        body_offset = index_end

    entries = []
    for i in range(count):
        eid, eoff, esize = struct.unpack_from("<III", entries_data, 12 * i)
        entries.append((eid, eoff, esize))

    body = data[body_offset:]

    repaired = []
    for eid, eoff, esize in entries:
        if eoff + esize <= len(body):
            repaired.append((eid, eoff, esize))
        elif eid == LMD_FILE_ID:
            idx = body.find(LMD_HEADER)
            if idx != -1 and idx + 36 <= len(body):
                lmdsize = struct.unpack_from("<I", body, idx + 32)[0]
                if idx + lmdsize <= len(body):
                    repaired.append((eid, idx, lmdsize))
                    continue
            print("[WARN] embedded local mix database is corrupted and cannot be recovered")
        else:
            print(f"[WARN] corrupted mix entry (data unreadable), skipped id={eid:08X}")
    entries = repaired

    lmd_mapper = {}
    for eid, eoff, esize in entries:
        if eid != LMD_FILE_ID:
            continue
        try:
            lmd_mapper = parse_lmd(body[eoff:eoff + esize])
        except ValueError:
            pass
        break

    names = []
    for eid, eoff, esize in entries:
        name = lmd_mapper.get(eid) or gmd_mapper.get(eid) or "%08X" % eid
        names.append((name, body[eoff:eoff + esize]))
    return names

def pack_directory(input_dir, output_file, password):

    password_bytes = password.encode('utf-8')
    if len(password_bytes) > 32:
        password_bytes = password_bytes[:32]
    else:
        password_bytes = password_bytes.ljust(32, b'\0')

    file_data = []
    index_entries = []
    current_offset = 0
    used_encrypted_names = set()

    gmd_mapper = get_ra2_gmd_mapper()

    def add_file(display_name, raw_data):
        nonlocal current_offset

        padded_data = pad(raw_data, AES.block_size)

        iv = b'\0' * 16
        cipher = AES.new(password_bytes, AES.MODE_CBC, iv)
        encrypted_data = cipher.encrypt(padded_data)

        encrypted_name = encrypt_filename(display_name, password)
        if encrypted_name in used_encrypted_names:
            print(f"[WARN] encrypted name of '{display_name}' collides with an existing entry; the loader may not distinguish them")
        used_encrypted_names.add(encrypted_name)

        file_data.append(encrypted_data)

        filename_padded = encrypted_name.encode('utf-8').ljust(32, b'\0')
        index_entry = filename_padded + struct.pack('<III', current_offset, len(encrypted_data), len(raw_data))
        index_entries.append(index_entry)

        print(f"[PACK] {display_name} | offset={current_offset}, enc={len(encrypted_data)}, raw={len(raw_data)}")
        current_offset += len(encrypted_data)

    for filename in sorted(os.listdir(input_dir)):
        filepath = os.path.join(input_dir, filename)
        if not os.path.isfile(filepath):
            continue

        if filename.lower().endswith('.mix'):

            try:
                with open(filepath, 'rb') as f:
                    raw_data = f.read()
                internals = parse_mix(raw_data, gmd_mapper)
            except Exception as e:
                print(f"[WARN] failed to parse '{filename}': {e}, packing raw file instead")
                with open(filepath, 'rb') as f:
                    add_file(filename, f.read())
            else:
                for name, data in internals:
                    if name.lower() == LMD_FILENAME:
                        print(f"[MIX] {filename} internal {name} (database metadata, skipped)")
                        continue
                    print(f"[MIX] {filename} -> {name}")
                    add_file(name, data)
            continue

        with open(filepath, 'rb') as f:
            add_file(filename, f.read())

    index_data = b''.join(index_entries)
    iv = b'\0' * 16
    index_cipher = AES.new(password_bytes, AES.MODE_CBC, iv)
    encrypted_index = index_cipher.encrypt(pad(index_data, AES.block_size))

    with open(output_file, 'wb') as f:

        f.write(b'RPCK')
        f.write(struct.pack('<I', len(encrypted_index)))
        f.write(encrypted_index)
        for data in file_data:
            f.write(data)

    print(f"[DONE] Packed {len(file_data)} files into '{output_file}'.")
    print(f"Actual password used: {password_bytes.decode('utf-8', errors='ignore')}")

def main():
    parser = argparse.ArgumentParser(
        description='Pack files into an encrypted resource pack (.mix files are parsed and their contents packed automatically).')
    parser.add_argument('input_dir', help='Input directory containing files to pack')
    parser.add_argument('output_file', help='Output resource pack file')
    parser.add_argument('password', help='32-char password string (used for both AES and filename encryption)')
    args = parser.parse_args()

    pack_directory(args.input_dir, args.output_file, args.password)

if __name__ == '__main__':
    main()
